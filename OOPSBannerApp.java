/**
 * OOPSBannerApp - Use Case 2
 * Prints OOPS in Banner Format using '*' and spaces.
 *
 * @author Shyam
 * @version 2.0
 */
public class OOPSBannerApp {

    public static void main(String[] args) {

        System.out.println("  *****  " + "  *****  " + " ******* " + " ******* ");
        System.out.println(" *     * " + " *     * " + " *      *" + " *       ");
        System.out.println(" *     * " + " *     * " + " *      *" + " *       ");
        System.out.println(" *     * " + " *     * " + " ******* " + "  *****  ");
        System.out.println(" *     * " + " *     * " + " *       " + "       * ");
        System.out.println(" *     * " + " *     * " + " *       " + "       * ");
        System.out.println("  *****  " + "  *****  " + " *       " + "  *****  ");
    }
}

